const UI_PATTERNS_EN = [
  [/^(\d+) kết quả$/i, '$1 results'],
  [/^(\d+) bản ghi$/i, '$1 records'],
  [/^(\d+) đơn cần xử lý$/i, '$1 orders to process'],
  [/^(\d+) sản phẩm sắp hết hàng$/i, '$1 low-stock products'],
  [/^(\d+) lượt đã dùng$/i, '$1 uses'],
  [/^(\d+)\/([\d,.]+) lượt đã dùng$/i, '$1/$2 uses'],
  [/^Còn lại$/i, 'Remaining'],
  [/^so với kỳ trước$/i, 'vs. previous period'],
  [/^Phiên bản\s+.+$/i, 'Version information'],
]

function preserveWhitespace(source, translated) {
  const leading = source.match(/^\s*/)?.[0] || ''
  const trailing = source.match(/\s*$/)?.[0] || ''
  return `${leading}${translated}${trailing}`
}

export function translateUiText(value, language = 'vi') {
  if (language !== 'en' || value == null) return value
  const source = String(value)
  const trimmed = source.trim()
  if (!trimmed) return source
  if (Object.prototype.hasOwnProperty.call(UI_EN, trimmed)) {
    return preserveWhitespace(source, UI_EN[trimmed])
  }
  for (const [pattern, replacement] of UI_PATTERNS_EN) {
    if (pattern.test(trimmed)) return preserveWhitespace(source, trimmed.replace(pattern, replacement))
  }
  return source
}
